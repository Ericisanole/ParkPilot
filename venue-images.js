// Park-specific exact matching keeps attractions with shared names separate.
function venueImageKey(name) { return String(name || '').normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/&/g,'and').replace(/[^a-z0-9]/g,''); }
function curatedVenueImage(name, park) {
  const key=venueImageKey(name);
  return VENUE_IMAGES.find(photo=>photo.park===park && [photo.name,...(photo.aliases||[])].some(alias=>venueImageKey(alias)===key)) || null;
}
function venueImageArt(photo, name, extraClass='') {
  const x=photo.columns===1?0:photo.column/(photo.columns-1)*100;
  const y=photo.rows===1?0:photo.row/(photo.rows-1)*100;
  return `<div class="venue-image-art ${ESC(extraClass)}" role="img" aria-label="${ESC(name)} photograph" style="--venue-image:url('${photo.atlas}');--venue-size:${photo.columns*100}% ${photo.rows*100}%;--venue-position:${x}% ${y}%;--venue-ratio:${photo.width}/${photo.height}"></div>`;
}
function venueImageCredit(photo) {
  return `<figcaption class="venue-image-credit"><a href="${ESC(photo.source)}" target="_blank" rel="noopener">${ESC(photo.artist)}</a> · <a href="${ESC(photo.licenseUrl)}" target="_blank" rel="noopener">${ESC(photo.license)}</a><span> · Cropped and resized</span></figcaption>`;
}
